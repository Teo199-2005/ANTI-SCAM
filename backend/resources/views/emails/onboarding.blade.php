    <h3>Business Eligibility</h3>
    <p>Resorts, hotels, staycation houses, villas, campsites, inns, Airbnb-style rentals and similar may register.</p>

    <h3>Registration & Property Submission</h3>
    <p>Owners must provide business details, property information, room details, and mandatory photos (minimum 5).</p>

    <h3>Verification Process</h3>
    <p>Verification methods include video call, on-site verification, and document review. Verification confirms existence and that documents/identity were checked; it does not guarantee guest satisfaction or ongoing standards.</p>

    <h3>Booking & Payment</h3>
    <p>Guests pay a ₱500 reservation/platform fee to Anti-ScamPH. Remaining accommodation balance is paid directly to the property. Anti-ScamPH does not take ownership, commissions, or manage property finances.</p>

